package com.example.model

import androidx.compose.ui.graphics.Color

enum class ConsoleFormFactor(val label: String) {
    HOME_CONSOLE("Home Console"),
    HANDHELD("Handheld Portable"),
    HYBRID("Hybrid Console / Handheld")
}

enum class ShadingPipeline(val title: String, val badge: String) {
    RETRO_8BIT_TILE("8-Bit Tile + Vector", "PPU-8"),
    DOT_MATRIX_LCD("4-Shade Olive LCD Grid", "DMG-LCD"),
    SUPER_FX_FLAT("Mode 7 + Super FX Flat Poly", "GSU-16"),
    PS1_AFFINE_WOBBLE("32-Bit Vertex Snap + Affine UV", "GTE-PSX"),
    N64_ZBUFFER_FOG("64-Bit Z-Buffer + 3-Pt Filter", "RCP-64"),
    HANDHELD_3D_RASTER("Portable Hardware 3D + Sprite", "ARM-3D"),
    CEL_ARCADE_128("128-Bit Cel-Shaded Specular", "PVR-128"),
    HD2D_VOXEL_BLOOM("Modern HD-2D Dynamic PBR + Sprite", "HD-2D")
}

data class ConsoleSpec(
    val id: String,
    val name: String,
    val shortCode: String,
    val releaseYear: Int,
    val manufacturer: String,
    val formFactor: ConsoleFormFactor,
    val generationLabel: String,
    val resolutionLabel: String,
    val virtualWidth: Int,
    val virtualHeight: Int,
    val maxColorsLabel: String,
    val polyBudgetLabel: String,
    val spriteHardwareLabel: String,
    val shadingPipeline: ShadingPipeline,
    val vertexSnapStrength: Float, // > 0 simulates PS1/Saturn/DS integer vertex jitter
    val pixelGridScale: Int,       // 1 = crisp HD, 2..5 = authentic low-res pixelation
    val hasScanlines: Boolean,
    val hasLcdSubpixelGrid: Boolean,
    val tintPalette: List<Color>,
    val stageFloorColor: Color,
    val stageSkyTop: Color,
    val stageSkyBottom: Color,
    val accentColor: Color
)

